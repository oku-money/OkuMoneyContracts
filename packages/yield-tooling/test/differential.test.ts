/**
 * Cross-language differential replay: TypeScript vs the Solidity reference.
 *
 * The sibling of `SVM/oku-programs/crates/oku-shared/tests/differential.rs`.
 * Both replay the same committed corpus; see that file's header for why the
 * three implementations must agree and why nothing on-chain can catch it if
 * they do not.
 *
 * This arm matters more than it might look. The TypeScript mirror is what the
 * epoch orchestrator uses to compute SVM's contribution to `V(t)` and what
 * `checkMultiplierDrift` uses to compare SVM against the EVM chains — Solana
 * has no view functions, so there is nothing to `call()`. A drift here would
 * silently mis-size every derived rate.
 *
 * Run: npm run test:tooling     (from the repo root)
 * Regenerate the corpus: cd EVM && forge test --match-contract GenerateVectors
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { computeMultiplier, rearmAnchor, type Schedule } from "../src/multiplier";

interface Vector {
  base: string;
  rate: string;
  anchor: string;
  rateEnd: string;
  pendingRate: string;
  pendingRateEnd: string;
  nowTs: string;
  reverted: boolean;
  expected: string;
}

const CORPUS = path.join(__dirname, "../../../EVM/test/differential/vectors.jsonl");

function loadCorpus(): Vector[] {
  if (!fs.existsSync(CORPUS)) {
    throw new Error(
      `cannot read differential corpus at ${CORPUS}.\n` +
        "Generate it with: cd EVM && forge test --match-contract GenerateVectors",
    );
  }
  return fs
    .readFileSync(CORPUS, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0)
    .map((l) => JSON.parse(l) as Vector);
}

function scheduleOf(v: Vector): Schedule {
  return {
    baseMultiplier: BigInt(v.base),
    ratePerSecond: BigInt(v.rate),
    lastAccrualTime: BigInt(v.anchor),
    rateEnd: BigInt(v.rateEnd),
    pendingRatePerSecond: BigInt(v.pendingRate),
    pendingRateEnd: BigInt(v.pendingRateEnd),
  };
}

test("computeMultiplier matches the Solidity reference exactly", () => {
  const vectors = loadCorpus();
  assert.ok(
    vectors.length > 1_000,
    `corpus looks truncated: only ${vectors.length} vectors. Regenerate it.`,
  );

  const mismatches: string[] = [];
  let revertCases = 0;

  vectors.forEach((v, i) => {
    const schedule = scheduleOf(v);
    const now = BigInt(v.nowTs);

    let threw = false;
    let actual: bigint | null = null;
    try {
      actual = computeMultiplier(schedule, now);
    } catch {
      threw = true;
    }

    if (v.reverted) {
      revertCases += 1;
      // Reverts are checked as strictly as values: "one implementation accepts
      // what another rejects" is just as much a divergence as a wrong number.
      if (!threw) {
        mismatches.push(`line ${i + 1}: Solidity REVERTED, TS returned ${actual}`);
      }
      return;
    }

    if (threw) {
      mismatches.push(`line ${i + 1}: Solidity returned ${v.expected}, TS threw`);
    } else if (actual !== BigInt(v.expected)) {
      mismatches.push(`line ${i + 1}: expected ${v.expected}, got ${actual}`);
    }
  });

  assert.equal(
    mismatches.length,
    0,
    `${mismatches.length} of ${vectors.length} vectors diverged from the ` +
      `Solidity reference:\n\n${mismatches.slice(0, 20).join("\n")}`,
  );

  // eslint-disable-next-line no-console
  // See the Rust twin: the revert half of the corpus can vanish silently.
  assert(
    revertCases >= 4,
    `corpus contains only ${revertCases} revert case(s) — the revert half of the ` +
      `differential has degraded. Regenerate with: cd EVM && forge test --match-contract GenerateVectors`,
  );

  console.log(
    `  differential: ${vectors.length} vectors matched (${revertCases} revert cases)`,
  );
});

/**
 * Re-arm anchor rule (Cyfrin audit #13): which `(base, anchor)` an admitted
 * `setOkuMYieldRate(newRate, newEnd)` stores. Generated by driving the real Solidity
 * contract (`GenerateRearmVectors.t.sol`); the Rust twin replays the same file.
 */
const REARM_CORPUS = path.join(__dirname, "../../../EVM/test/differential/rearm-vectors.jsonl");

test("rearmAnchor matches the Solidity reference exactly", () => {
  if (!fs.existsSync(REARM_CORPUS)) {
    throw new Error(
      `cannot read re-arm corpus at ${REARM_CORPUS}.\n` +
        "Generate it with: cd EVM && forge test --match-contract GenerateVectors",
    );
  }
  const lines = fs
    .readFileSync(REARM_CORPUS, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0);
  assert.ok(lines.length > 3_000, `re-arm corpus looks truncated: ${lines.length} vectors`);

  const mismatches: string[] = [];
  let kept = 0;
  let promoted = 0;
  lines.forEach((l, i) => {
    const v = JSON.parse(l) as Vector & {
      newRate: string;
      newEnd: string;
      expectedBase: string;
      expectedAnchor: string;
    };
    const s = scheduleOf(v);
    const got = rearmAnchor(s, BigInt(v.nowTs), BigInt(v.newRate), BigInt(v.newEnd));
    if (got.baseMultiplier !== BigInt(v.expectedBase) || got.lastAccrualTime !== BigInt(v.expectedAnchor)) {
      mismatches.push(
        `line ${i + 1}: Solidity stored (${v.expectedBase}, ${v.expectedAnchor}), ` +
          `TS (${got.baseMultiplier}, ${got.lastAccrualTime})`,
      );
    }
    const anchor = BigInt(v.expectedAnchor);
    if (anchor !== BigInt(v.nowTs) && anchor === s.lastAccrualTime) kept++;
    else if (anchor !== BigInt(v.nowTs) && anchor === s.rateEnd) promoted++;
  });

  assert.equal(
    mismatches.length,
    0,
    `${mismatches.length} of ${lines.length} re-arm vectors diverged from the Solidity ` +
      `reference:\n\n${mismatches.slice(0, 20).join("\n")}`,
  );
  assert.ok(kept > 100 && promoted > 100, `re-arm corpus lost a rule: keep ${kept}, promote ${promoted}`);
  console.log(`  re-arm differential: ${lines.length} vectors matched (keep ${kept}, promote ${promoted})`);
});
