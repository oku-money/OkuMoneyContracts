/**
 * Testnet address registry sync (SVM side)
 *
 * Writes the current SVM deployment into the repo-root `testnet-addresses.json`
 * file, which is the canonical human-readable address registry for all chains.
 *
 * The EVM side has a matching sync helper in its own scripts/utils tree. Each
 * side only updates its own section of the file, preserving the other side.
 *
 * Called from deploy-init.ts after saveDeployment(). Safe to call multiple
 * times (idempotent, last-write-wins per network).
 */

import * as fs from 'fs';
import * as path from 'path';
import type { DeploymentAddresses } from './addressBook';

const REGISTRY_PATH = path.resolve(__dirname, '../../../../testnet-addresses.json');

export interface SvmNetworkEntry {
  // SVM has no EIP-155-style chain ID and carries no on-chain chain-ID state.
  rpcUrl?: string;
  explorer?: string;
  programs: Record<string, string | undefined>;
  mints: Record<string, string | undefined>;
  pdas: Record<string, string | undefined>;
  authorities?: Record<string, string | undefined>;
}

interface TestnetRegistry {
  _comment?: string;
  lastUpdated?: string;
  evm?: Record<string, unknown>;
  svm?: Record<string, SvmNetworkEntry>;
}

const DISCLAIMER =
  'Auto-generated by EVM/SVM deploy scripts. Do not hand-edit; run a deploy to refresh.';

function loadRegistry(): TestnetRegistry {
  if (!fs.existsSync(REGISTRY_PATH)) {
    return {};
  }
  try {
    return JSON.parse(fs.readFileSync(REGISTRY_PATH, 'utf8'));
  } catch (error) {
    console.warn(`[testnetRegistry] Could not parse ${REGISTRY_PATH}:`, error);
    return {};
  }
}

function writeRegistry(registry: TestnetRegistry): void {
  registry._comment = DISCLAIMER;
  registry.lastUpdated = new Date().toISOString();
  fs.writeFileSync(REGISTRY_PATH, JSON.stringify(registry, null, 2) + '\n', 'utf8');
}

// RPC URLs are kept here because they're a registry-only concern and not
// part of the on-chain config. There is no on-chain chain-ID state.
const SVM_CLUSTER_RPC: Record<string, string> = {
  'mainnet-beta': 'https://api.mainnet-beta.solana.com',
  devnet: 'https://api.devnet.solana.com',
  'devnet-fork': 'http://127.0.0.1:8899',
  'mainnet-fork': 'http://127.0.0.1:8899',
  localnet: 'http://127.0.0.1:8899',
};

/**
 * Update the SVM section of the registry for a given network from a
 * DeploymentAddresses object. Leaves the EVM section untouched.
 */
export function syncSvmRegistry(deployment: DeploymentAddresses): void {
  const registry = loadRegistry();
  registry.svm = registry.svm || {};

  const entry: SvmNetworkEntry = {
    rpcUrl: SVM_CLUSTER_RPC[deployment.network],
    programs: {
      litePsm: deployment.programs?.litePsm,
    },
    mints: {
      usdc: deployment.tokens?.usdc,
      okuM: deployment.tokens?.okuM,
    },
    pdas: {
      psmConfig: deployment.pdas?.psmConfig,
      psmOkuMEscrow: deployment.pdas?.psmOkuMEscrow,
      psmVaultUsdc: deployment.pdas?.psmVaultUsdc,
    },
    authorities: deployment.authorities,
  };

  registry.svm[deployment.network] = entry;
  writeRegistry(registry);
  console.log(
    `[testnetRegistry] Wrote SVM.${deployment.network} → ${path.relative(process.cwd(), REGISTRY_PATH)}`
  );
}
