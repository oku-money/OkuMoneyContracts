/**
 * Testnet address registry sync (EVM side)
 *
 * Writes the current EVM deployment into the repo-root `testnet-addresses.json`
 * file, which is the canonical human-readable address registry for all chains.
 *
 * The SVM side has a matching sync helper in its own scripts/utils tree. Each
 * side only updates its own section of the file, preserving the other side.
 *
 * Called from the EVM deploy script after a successful deployment. Safe to call
 * multiple times (idempotent, last-write-wins per network).
 */

import fs from "fs";
import path from "path";

const REGISTRY_PATH = path.resolve(__dirname, "../../../testnet-addresses.json");

export interface EvmNetworkEntry {
  chainId: number;
  rpcUrl: string;
  explorer?: string;
  contracts: {
    okuM?: string;
    usdOku?: string;
    litePSM?: string;
    mockUSDC?: string;
    // redemptionQueue / okuBridge / okuBridgeRouter were removed from the design;
    // the open-ended index keeps historical entries readable without re-typing them.
    [key: string]: string | undefined;
  };
  orchestrator?: string;
  deployer?: string;
}

interface TestnetRegistry {
  _comment?: string;
  lastUpdated?: string;
  evm?: Record<string, EvmNetworkEntry>;
  svm?: Record<string, unknown>;
}

const DISCLAIMER =
  "Auto-generated by EVM/SVM deploy scripts. Do not hand-edit; run a deploy to refresh.";

function loadRegistry(): TestnetRegistry {
  if (!fs.existsSync(REGISTRY_PATH)) {
    return {};
  }
  try {
    return JSON.parse(fs.readFileSync(REGISTRY_PATH, "utf8"));
  } catch (error) {
    console.warn(`[testnetRegistry] Could not parse ${REGISTRY_PATH}:`, error);
    return {};
  }
}

function writeRegistry(registry: TestnetRegistry): void {
  registry._comment = DISCLAIMER;
  registry.lastUpdated = new Date().toISOString();
  fs.writeFileSync(REGISTRY_PATH, JSON.stringify(registry, null, 2) + "\n", "utf8");
}

/**
 * Update the EVM section of the registry for a given network. Leaves the SVM
 * section untouched.
 */
export function syncEvmRegistry(network: string, entry: EvmNetworkEntry): void {
  const registry = loadRegistry();
  registry.evm = registry.evm || {};
  registry.evm[network] = entry;
  writeRegistry(registry);
  console.log(
    `[testnetRegistry] Wrote EVM.${network} → ${path.relative(process.cwd(), REGISTRY_PATH)}`
  );
}
